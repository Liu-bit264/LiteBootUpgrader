#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""bl_upgrade.py — LiteBootLoader 上位机 v1.4.0（独立仓库 LiteBootUpgrader）

协议见 docs/protocol.md：
  SOF(AA 55) | VER(01) | CMD | SEQ | LEN(LE16) | DATA(0..256B) | CRC16(LE16,MODBUS) | EOF(55 AA)
CRC 覆盖 VER..DATA；响应 CMD = 请求 CMD|0x80，DATA[0] = 状态码。
连接类型：--conn serial（有线串口，默认）| bt（蓝牙 SPP/HC-05，打开失败自动重试）；
模块需一次性 AT 配置数据模式到 115200（主仓 docs/dev/bluetooth_notes.md §5）。

签名验签（1.4.0，ADR-020）：`keygen` 子命令生成 P-256 测试密钥对（私钥 PEM +
公钥本地头 bl_sign_pubkey_local.h——任何形态不入库）；`upgrade --key <pem>` 在
写块完成后改发 0x11 VERIFY_SIGNED（固件需 BL_SIGN_EN=1 且公钥配对，auth 置位
方可跳转；篡改镜像将回 SIGN_ERROR 且不持久化）。

主机侧重试约定（protocol.md §6）：单命令响应超时 1000 ms（ERASE/VERIFY 5000 ms），
超时后重发至多 3 次尝试（首发 1 + 重发 ≤2），重试间隔 2.2 s（等待 BL 帧内 2000 ms 超时复位解析器）。
upgrade 会自动识别对端：若 APP 正在运行，先走"请求回 BL"流程（SET_META bl_request）
再升级——从任意状态一条命令完成升级。

依赖隔离（建议隔离运行，勿直接 pip install 到全局）：
  uv run --python 3.12 --with pyserial bl_upgrade.py selftest --port COM4
  签名功能（keygen / upgrade --key）另需：
  uv run --python 3.12 --with pyserial --with cryptography bl_upgrade.py keygen
"""
