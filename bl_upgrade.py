def ensure_bl(bl: BootLoader, log=print) -> bool:
    """确认对端处于 BL；APP 在跑则自动走'请求回 BL'流程（external_interface.md §5）。"""
    log("探测对端…")
    for attempt in range(RETRY_ATTEMPTS):
        r = bl.cmd("info", timeout=T_DEFAULT)
        if r is not None:
            st = _resp_status(r, "GET_INFO")
            if st == 0x00:
                log("对端 = BL ✓")
                return True
            if st == 0x03:      # APP 响应器只认 PING/SET_META，其余回 RANGE_ERROR
                log("对端 = APP，发送 bl_request 请求回 BL…")
                r2 = bl.cmd("set_meta", bytes([0x01, 0x01]), timeout=T_DEFAULT)
                r2st = _resp_status(r2, "SET_META")
                log("APP 已确认请求" if r2st == 0
                    else "APP 未按预期确认（继续等待复位）")
                log("等待复位进入 BL（1.6s）…")
                time.sleep(1.6)
                continue        # 重新探测
            log(f"[X] 对端响应异常 status={st_name(st)}")
            return False
        if attempt < RETRY_ATTEMPTS - 1:
            # 无响应可能是 BL 解析器卡在半帧，等帧内超时复位后再试
            log(f"    [!] 探测无响应，{RETRY_DELAY:.1f}s 后重试（{attempt + 2}/{RETRY_ATTEMPTS}）")
            time.sleep(RETRY_DELAY)
    log("[X] 无法确认对端为 BL")
    return False


def run_upgrade(bl: BootLoader, path: str, log=print, progress=None,
                key_path: str | None = None) -> int:
    """一键升级完整流程（protocol.md §7 主机侧约定的唯一实现）：
    ensure_bl → ERASE → 逐块 WRITE → VERIFY / VERIFY_SIGNED。
    key_path 非 None 时走签名校验（0x11，固件需 BL_SIGN_EN=1 且公钥配对）。
    progress(done, total) 在每个块成功后回调（GUI 用）；返回 0=成功。"""
    with open(path, "rb") as f:
        img = f.read()
    if len(img) == 0 or len(img) > APP_SIZE:
        raise ValueError(f"镜像大小 {len(img)} 超出 1B~{APP_SIZE}B")
    if len(img) % 4:
        img += b"\xFF" * (4 - len(img) % 4)     # VERIFY 要求 4 字节对齐
    crc = zlib.crc32(img) & 0xFFFFFFFF
    log(f"镜像 {len(img)}B crc32={crc:#010x}")

    if not ensure_bl(bl, log=log):
        return 1

    log("擦除 APP 区…")
    r = bl.cmd_retry("erase", timeout=T_ERASE, log=log)
    st = _resp_status(r, "erase")
    log("erase:", st_name(st) if st is not None else "无响应（重试耗尽）")
    if st is None or st:
        return 1
    total = len(img)
    for off in range(0, total, CHUNK_PAYLOAD):
        r = bl.cmd_retry("write", struct.pack("<I", off) + img[off:off + CHUNK_PAYLOAD],
                         timeout=2.0, log=log)
        st = _resp_status(r, "write")
        if st is None or st:
            log(f"write @{off} 失败: "
                f"{st_name(st) if st is not None else '无响应（重试耗尽）'}")
            return 1
        if progress:
            progress(min(off + CHUNK_PAYLOAD, total), total)
    if key_path:
        sig = sign_image_bytes(img, key_path)
        log("验签…（VERIFY_SIGNED，ADR-020）")
        r = bl.cmd_retry("verify_signed", struct.pack("<II", total, crc) + sig,
                         timeout=T_VERIFY, log=log)
        st = _resp_status(r, "verify_signed")
        if st == 0:
            if len(r["data"]) < 9:
                raise RuntimeError(f"verify_signed 响应 DATA 过短："
                                   f"{len(r['data'])}B < 9B（对端异常）")
            calc, csize = struct.unpack_from("<II", r["data"], 1)
            log(f"verify_signed: OK crc={calc:#010x} size={csize} "
                f"—— auth 置位，APP 就绪，可 jump")
            return 0
        log("verify_signed 失败:", st_name(st) if st is not None else "无响应（重试耗尽）")
        if st == 0x06:
            log("[!] SIGN_ERROR：镜像或签名与固件公钥不符——未持久化（auth=0，拒绝跳转）；"
                "确认固件为 BL_SIGN_EN=1 构建且 --key 与其公钥配对")
        return 1
    log("校验…")
    r = bl.cmd_retry("verify", struct.pack("<II", total, crc), timeout=T_VERIFY, log=log)
    st = _resp_status(r, "verify")
    if st == 0:
        if len(r["data"]) < 9:
            # status + calc_crc32 + calc_size 最少 9B（review 2026-09-27 P2）
            raise RuntimeError(f"verify 响应 DATA 过短：{len(r['data'])}B < 9B（对端异常）")
        calc, csize = struct.unpack_from("<II", r["data"], 1)
        log(f"verify: OK crc={calc:#010x} size={csize} —— APP 就绪，可 jump")
        return 0
    log("verify 失败:", st_name(st) if st is not None else "无响应（重试耗尽）")
    return 1


def cmd_upgrade(bl: BootLoader, path: str, key_path: str | None = None) -> int:
    try:
        return run_upgrade(bl, path, key_path=key_path)
    except ValueError as e:
        sys.exit(f"[X] {e}")
    except RuntimeError as e:
        sys.exit(f"[X] {e}")     # 对端异常响应的友好退出（review 2026-09-27 P2）
    except OSError as e:
        sys.exit(f"[X] 打开镜像失败：{e}")


def build_parser():
    ap = argparse.ArgumentParser(description=f"LiteBootLoader 上位机 v{VERSION}（LiteBootUpgrader）")
    ap.add_argument("command",
                    choices=["ping", "info", "meta", "erase", "verify",
                             "upgrade", "jump", "reset", "selftest",
                             "listen", "raw", "setmeta", "ota", "keygen"])
    ap.add_argument("arg", nargs="?", help="upgrade: 镜像文件；verify: size")
    ap.add_argument("arg2", nargs="?", help="verify: crc32 十六进制")
    ap.add_argument("--port", default="COM4")
    ap.add_argument("--baud", type=int, default=115200)
    ap.add_argument("--pace", type=int, default=0,
                    help="命令间插入延时（ms），用于时序假设验证")
    ap.add_argument("--conn", choices=["serial", "bt"], default="serial",
                    help="连接类型：serial=有线串口（默认）；bt=蓝牙 SPP（HC-05，"
                         "打开失败自动重试）")
    ap.add_argument("--key", help="upgrade：ECDSA P-256 私钥 PEM——启用签名校验"
                                 "（0x11 VERIFY_SIGNED，固件需 BL_SIGN_EN=1 且公钥配对）")
    ap.add_argument("--out-key", default="sign_test_key.pem",
                    help="keygen：私钥 PEM 输出路径（默认 ./sign_test_key.pem）")
    ap.add_argument("--out-header",
                    help="keygen：公钥本地头输出路径（bl_sign_pubkey_local.h，"
                         "指向固件仓芯片端口目录；缺省仅打印到 stdout）")
    ap.add_argument("--version", action="version",
                    version=f"LiteBootUpgrader v{VERSION}")
    return ap


def main():
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass
    a = build_parser().parse_args()

    if a.command == "selftest":
        sys.exit(selftest(BootLoader(a.port, a.baud, a.pace, a.conn)))
    if a.command == "keygen":
        sys.exit(cmd_keygen(a.out_key, a.out_header))

    bl = BootLoader(a.port, a.baud, a.pace, a.conn)
    try:
        if a.command == "ping":
            r = bl.cmd("ping")
            print("无响应" if r is None else
                  f"status={st_name(r['data'][0])} proto_ver={r['data'][1]:#04x}")
        elif a.command == "info":
            r = bl.cmd("info")
            print("无响应" if r is None else parse_info(r["data"]))
        elif a.command == "ota":
            r = bl.cmd("ota", timeout=2.0)
            if r is None:
                print("无响应")
            else:
                try:
                    print(parse_ota(r["data"]))
                except RuntimeError as e:
                    print(f"ota: {e}")
        elif a.command == "meta":
            r = bl.cmd("get_meta")
            print("无响应" if r is None else meta_str(parse_meta(r["data"])))
        elif a.command == "erase":
            t0 = time.time()
            r = bl.cmd("erase", timeout=8.0)
            print("无响应" if r is None else
                  f"erase: {st_name(r['data'][0])} 耗时={time.time() - t0:.2f}s")
        elif a.command == "upgrade":
            if not a.arg:
                sys.exit("用法：upgrade <镜像文件> [--key <pem>]")
            sys.exit(cmd_upgrade(bl, a.arg, key_path=a.key))
        elif a.command == "verify":
            if not a.arg or not a.arg2:
                sys.exit("用法：verify <size> <crc32_hex>")
            r = bl.cmd("verify", struct.pack("<II", int(a.arg, 0), int(a.arg2, 16)),
                       timeout=3.0)
            print("无响应" if r is None else
                  f"verify: {st_name(r['data'][0])}")
        elif a.command == "listen":
            secs = float(a.arg) if a.arg else 3.0
            t0 = time.time()
            buf = bytearray()
            while time.time() - t0 < secs:
                chunk = bl.s.read(256)
                if chunk:
                    buf += chunk
            text = buf.decode("utf-8", "replace")
            if text.strip():
                print(text, end="")
            print(f"({secs:.0f}s 监听结束)")
        elif a.command == "raw":
            if not a.arg:
                sys.exit("用法：raw <hex 字节，如 42>")
            data = bytes.fromhex(a.arg.replace(" ", ""))
            bl.send_raw(data)
            print(f"已发送 {len(data)}B 原始字节")
        elif a.command == "setmeta":
            if not a.arg or not a.arg2:
                sys.exit("用法：setmeta <field_hex> <value_hex>")
            r = bl.cmd("set_meta", bytes([int(a.arg, 16), int(a.arg2, 16)]))
            print("无响应" if r is None else
                  f"set_meta({a.arg},{a.arg2}): {st_name(r['data'][0])}")
            t0 = time.time()
            buf = bytearray()
            while time.time() - t0 < 3.0:
                chunk = bl.s.read(256)
                if chunk:
                    buf += chunk
            text = buf.decode("utf-8", "replace")
            if text.strip():
                print("--- 后续串口输出 ---\n" + text, end="")
        elif a.command in ("jump", "reset"):
            follow = 6.0 if a.command == "reset" else 2.5
            r = bl.cmd(a.command, timeout=2.0)
            if r is None:
                print(f"{a.command}: 无响应")
                return
            print(f"{a.command}: {st_name(r['data'][0])}"
                  + ("（APP 无效被拒绝）" if r["data"][0] == 0x04 else ""))
            if r["data"][0] != 0x00:
                return
            t0 = time.time()
            buf = bytearray()
            while time.time() - t0 < follow:
                chunk = bl.s.read(256)
                if chunk:
                    buf += chunk
            text = buf.decode("utf-8", "replace")
            if text.strip():
                print("--- 串口输出 ---\n" + text, end="")
    except (RuntimeError, IndexError) as e:
        # 对端返回 CRC 合法但长度异常的响应时的兜底（审计 2026-09-29 P3-2）：
        # 现网 BL/APP 不会产生此类响应，友好退出而非栈回溯
        sys.exit(f"[X] {e}")


if __name__ == "__main__":
    main()
